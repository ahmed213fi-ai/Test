// Concatenates src/ into ONE classic script (game.bundle.js) for previewers that
// can't run ES modules. src/ stays the source of truth; re-run after editing it.
import { readFileSync, writeFileSync } from 'node:fs';

const ORDER = [
  'config/constants.js', 'config/hints.js', 'config/enemies.js', 'config/weapons.js', 'config/pickups.js', 'config/waves.js',
  'systems/SaveManager.js', 'systems/TextureFactory.js', 'systems/Background.js', 'systems/device.js', 'systems/joystickMath.js', 'systems/homing.js', 'systems/Shop.js',
  'entities/Bullet.js', 'entities/Alien.js', 'entities/Pickup.js', 'entities/Player.js',
  'systems/WeaponSystem.js', 'systems/Formation.js', 'systems/Controls.js', 'systems/Hints.js',
  'ui/style.js', 'ui/Hud.js', 'ui/Button.js',
  'scenes/BootScene.js', 'scenes/MainMenuScene.js', 'scenes/SettingsScene.js', 'scenes/ArmoryScene.js', 'scenes/GameOverScene.js', 'scenes/PauseScene.js', 'scenes/GameScene.js',
  'main.js',
];

function strip(src, file) {
  if (/import\.meta/.test(src)) throw new Error(`${file}: import.meta cannot be bundled`);
  const out = src
    .split('\n')
    .filter((line) => !/^import\s.+\sfrom\s.+;\s*$/.test(line))
    .join('\n')
    .replace(/^export default (class|function)/gm, '$1')
    .replace(/^export (const|let|class|function)/gm, '$1');
  if (/^\s*(import|export)\s/m.test(out)) throw new Error(`${file}: unsupported import/export syntax left over`);
  return out;
}

let out = "// AUTO-GENERATED by scripts/bundle.mjs - do not edit. Source of truth: src/\n(function () {\n'use strict';\n";
for (const f of ORDER) {
  out += `\n// ---- ${f} ----\n${strip(readFileSync(new URL(`../src/${f}`, import.meta.url), 'utf8'), f)}\n`;
}
out += '\n})();\n';
writeFileSync(new URL('../game.bundle.js', import.meta.url), out);
console.log(`game.bundle.js written (${out.length} bytes, ${ORDER.length} modules)`);
